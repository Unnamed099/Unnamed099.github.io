; ============================================================
;  boot.asm - 专业级引导程序（支持彩色输出、加载内核）
;  编译: nasm -f bin boot.asm -o boot.bin
;  大小: 512 字节（引导扇区）
; ============================================================

org 0x7C00
bits 16

; ---------- 入口点 ----------
start:
    ; 1. 设置运行环境
    xor ax, ax
    mov ds, ax          ; DS = 0x0000
    mov es, ax          ; ES = 0x0000
    mov ss, ax          ; SS = 0x0000
    mov sp, 0x7C00      ; 栈从 0x7C00 向下生长（安全区域）

    ; 2. 清屏（设置视频模式 80x25 彩色文本）
    mov ax, 0x0003
    int 0x10

    jmp $

times 510 - ($ - $$) db 0
dw 0xAA55               ; 引导签名